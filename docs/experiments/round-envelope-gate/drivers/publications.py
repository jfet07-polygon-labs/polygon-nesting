#!/usr/bin/env python3
"""Every layout the matched gate published, re-asked of both authorities.

    publications.py MATCHEDJSON RUNSDIR OUTDIR PLANOUT

Sol review 12 §3.2's promotion rule has a clause the arm's own report cannot
answer - *"every arm publication passes the untouched material contract
validator"* - and a kill the arm's own report cannot answer either - *"any false
accept anywhere"*. Both are questions about the published **layout**, so they are
asked of the layout, by the instrument the previous round built for exactly this:
`round_envelope_gate::wired_verdicts`, which goes through
`validate_and_measure_placements` - the real wire point - rather than around it.

This driver takes each mode-34 run's own `placements` array, writes it as a pose
fixture, and emits a battery plan whose `canonicalCorpus` is those publications.
The battery then reports, per layout:

* `compositeMiterVerdict`  - HEAD's authority. A publication the miter refuses
  and the union accepts is a **new admission**, and its depth is what the kill
  about the contact-block 0.5 mm class is measured on.
* `compositeUnionVerdict`  - the armed authority. Accepting implies the
  untouched contract accepted, because the wire point runs the contract on both
  of its branches and returns `Err` if it refuses.
* `compositeRoundVerdict`  - the exclusive kernel, reported for the record.

The sweep and economy sections are set to their smallest legal size: this plan
is not the soundness battery, it is the corpus section pointed at this round's
own output, and the previous round's battery is the soundness evidence.
"""
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__),
                                    '..', '..', '..', '..'))
POSE_KEYS = ('pieceId', 'rotationDeg', 'mirrored', 'translateShortAxis',
             'translateLongAxis')


def sources(document):
    """`(tag, run-document-basename, metadata)` for either driver's output.

    `matchedgate.py` writes cells keyed by seed with an arm map;
    `coordarm.py` writes a flat row list with its own `tag`. Both name their run
    document after the tag, which is what makes one reader enough.
    """
    if 'cells' in document:
        for cell in document['cells']:
            seed = cell['seed']
            for label, row in cell['arms'].items():
                arm, _, work = label.partition(':')
                tag = f'seed{seed}-{arm}-{work}'
                yield tag, tag, {
                    'seed': seed, 'arm': arm, 'workCap': int(work),
                    'rawSourceDepthMm': row.get('rawSourceDepthMm'),
                    'fingerprint': row.get('fingerprint'),
                    'exactValid': row.get('exactValid'),
                    'contractValid': row.get('contractValid'),
                    'reportedKernelMode': row.get('reportedKernelMode'),
                }
        return
    for row in document.get('rows', []):
        yield row['tag'], row['tag'], {
            'seed': row.get('seed'), 'arm': row.get('arm'),
            'round': row.get('round'), 'budget': row.get('budget'),
            'spec': row.get('spec'),
            'rawSourceDepthMm': row.get('rawDepthMm'),
            'dualGateValid': row.get('dualGateValid'),
            'reportedKernelMode': row.get('reportedKernelMode'),
        }


def main():
    matched_path, runs_dir, outdir, plan_out = sys.argv[1:5]
    matched = json.load(open(matched_path))
    os.makedirs(outdir, exist_ok=True)
    corpus = []
    index = {}
    for tag, basename, meta in sources(matched):
        doc_path = f'{runs_dir}/{basename}.json'
        if not os.path.exists(doc_path):
            continue
        doc = json.load(open(doc_path))
        placements = doc.get('placements')
        if not placements:
            continue
        fixture = {
            'schemaVersion': 1,
            'description': f'{tag}: the layout this run published',
            'placements': [{k: pose[k] for k in POSE_KEYS}
                           for pose in placements],
        }
        path = f'{outdir}/{tag}-publication.json'
        json.dump(fixture, open(path, 'w'), indent=1)
        corpus.append({'label': tag, 'path': path})
        index[tag] = meta
    plan = {
        '_note': ('The matched gate\'s own publications, re-asked of both '
                  'authorities through `validate_and_measure_placements`. '
                  'Generated by drivers/publications.py; the fixtures under '
                  '/var/lib/t3/tmp are this round\'s run outputs.'),
        'request': f'{ROOT}/tests/fixtures/mixed-61/'
                   'mixed61-request-exact-clearance.json',
        'edgeClearanceMm': 5.0,
        'pairClearanceMm': 5.0,
        # The allowance the matched gate ran at, and nothing else: a
        # publication is legal or not at the allowance it was made under.
        'corpusAllowancesMm': [0.002],
        'canonicalCorpus': corpus,
        'sparrow': {
            'path': f'{ROOT}/docs/experiments/gate-a-sparrow-import/fixture/'
                    'sparrow-10s-x86-poses.json',
            'allowancesMm': [0.002, 0.0005, 0.0],
        },
        'sweeps': {'sources': [corpus[0]['label']] if corpus else [],
                   'pairsPerSource': 1, 'boundariesPerSource': 1,
                   'stepsEachWay': 1},
        'economy': {'sources': [corpus[0]['label']] if corpus else [],
                    'repetitions': 1},
        'reportTop': 6,
    }
    json.dump(plan, open(plan_out, 'w'), indent=1)
    json.dump(index, open(f'{outdir}/publication-index.json', 'w'), indent=1)
    print(json.dumps({'publications': len(corpus), 'plan': plan_out}, indent=1))


if __name__ == '__main__':
    main()
