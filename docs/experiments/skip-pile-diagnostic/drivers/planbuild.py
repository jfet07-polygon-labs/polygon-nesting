#!/usr/bin/env python3
"""Builds the scoring plan from the dump ladder's own output.

    planbuild.py DUMPLADDERJSON PLANOUT [SAMPLE] [CENSUS] [REPORTTOP]

`SAMPLE` is per cell and is the scoring budget, because a full double census is
1830 exact pair tests plus 1830 Clipper overlap tests and the pile is fourteen
thousand frontiers deep. `CENSUS` is how many of those sampled records also get
the full per-pair scan; every record whose two envelopes *disagree* gets one
regardless, so the budget only decides how many agreeing records are described.

The plan carries each cell's committed `confirmationsSkippedInfeasible` as
`expectedSkips`, so the scoring document itself re-states the reproduction
rather than pointing at another file for it.

`edgeClearanceMm` and `pairClearanceMm` are 5.0/5.0 - the exact-clearance
contract the twelve pinned parents live under - and the allowances are the
`0.002` the ladder actually ran at and the `0.0` contract radius, which are the
2.502 mm and 2.500 mm collision expansions the question is written in.
"""
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__),
                                    '..', '..', '..', '..'))
DEFAULT_SAMPLE = 300
DEFAULT_CENSUS = 60
DEFAULT_REPORT_TOP = 6


def main():
    ladder_path, plan_out = sys.argv[1], sys.argv[2]
    sample = int(sys.argv[3]) if len(sys.argv) > 3 else DEFAULT_SAMPLE
    census = int(sys.argv[4]) if len(sys.argv) > 4 else DEFAULT_CENSUS
    report_top = int(sys.argv[5]) if len(sys.argv) > 5 else DEFAULT_REPORT_TOP
    ladder = json.load(open(ladder_path))
    cells = []
    for cell in ladder['cells']:
        cells.append({
            'label': cell['label'],
            'path': cell['dumpPath'],
            'sample': sample,
            'expectedSkips': cell['measured'].get(
                'schedule_confirmationsSkippedInfeasible'),
        })
    plan = {
        '_note': ('The skip pile, scored by the material contract, by HEAD\'s '
                  'miter authority and by the certified disc kernel. '
                  'Generated by drivers/planbuild.py from the dump ladder; '
                  'the JSONL under /var/lib/t3/tmp is this round\'s dump.'),
        'request': f'{ROOT}/tests/fixtures/mixed-61/'
                   'mixed61-request-exact-clearance.json',
        'edgeClearanceMm': 5.0,
        'pairClearanceMm': 5.0,
        # 0.002 is the allowance the skip happened at (expansion 2.502 mm);
        # 0.0 is the contract radius itself (2.500 mm).
        'allowancesMm': [0.002, 0.0],
        'censusAllowanceMm': 0.002,
        'censusBudget': census,
        'reportTop': report_top,
        'cells': cells,
    }
    json.dump(plan, open(plan_out, 'w'), indent=1)
    print(json.dumps({'plan': plan_out, 'cells': len(cells),
                      'samplePerCell': sample, 'censusPerCell': census,
                      'expectedSkipsTotal': sum(
                          c['expectedSkips'] or 0 for c in cells)}, indent=1))


if __name__ == '__main__':
    main()
